export function InterfaceLanguageProvider({ language, children }) {
  const translate = useMemo(() => (text) => {
    if (language !== 'en') return text;
    if (englishText[text]) return englishText[text];
    const prefix = Object.keys(englishText).find((key) => key.endsWith(' ') && text.startsWith(key));
    return prefix ? `${englishText[prefix]}${text.slice(prefix.length)}` : text;
  }, [language]);

  return createElement(InterfaceLanguageContext.Provider, { value: translate }, children);
}

export function useInterfaceText() {
  return useContext(InterfaceLanguageContext);
}
